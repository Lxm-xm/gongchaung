/**
 * @file    link_test.h
 * @brief   USART1 通信链路的"最小闭环"验收程序
 *
 * ── 这一轮只做三件事，故意不做业务 ────────────────────────────────────
 *   1) 把串口收到的字节喂给拆帧状态机
 *   2) 收到一帧合法数据 → 回一个 ACK
 *   3) 每 500ms 主动发一次心跳
 *
 * ── 为什么先做这么少 ──────────────────────────────────────────────────
 *   故障隔离。如果一上来就写"解析航点→启动任务→电机转"，
 *   链路不通时你有 5 个可能原因（串口/波特率/CRC/解析/业务），要试一天。
 *   只回 ACK，可能原因只剩 3 个，而且有明确判据：
 *     发对帧不回 → 串口或波特率问题
 *     发错帧也回 → CRC 没生效（范围算错）
 *     两个都对   → 协议层可信，可以往上加业务
 */
#ifndef LINK_TEST_H
#define LINK_TEST_H

/**
 * @brief 初始化：重置拆帧状态机 + 启动 USART1 接收
 * @note  在任务里、MX_USART1_UART_Init() 之后调用一次。
 */
void LinkTest_Init(void);

/**
 * @brief 主循环体：收帧 + 定时发心跳
 * @note  每 20ms 调一次。
 *        20ms 是权衡：115200 下一周期最多积压 230 字节（缓冲 512 够用），
 *        而每秒只唤醒 50 次，CPU 开销可忽略。
 */
void LinkTest_Step(void);

#endif /* LINK_TEST_H */
