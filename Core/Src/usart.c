/**
  * @brief  串口接收完成回调（由 HAL 在中断上下文里调用）
  *
  * ── 调用链 ──────────────────────────────────────────────────────────
  *   一个字节到达
  *     → 硬件置 RXNE 标志
  *     → 进 USART1_IRQHandler（在 stm32f4xx_it.c 里）
  *     → HAL_UART_IRQHandler(&huart1)
  *     → 本函数
  *     → Uart1_OnRxByteFromIsr()（把字节存进环形缓冲）
  *
  * ── 为什么这里只做"转交"，不做解析 ──────────────────────────────────
  *   这是中断上下文，它抢占一切，包括以后 20ms 的底盘控制任务。
  *   所以必须极短：只把字节搬走就返回。拆帧、CRC 这些留给任务做。
  *
  * ── 为什么参数里拿不到那个字节 ─────────────────────────────────────
  *   单字节中断模式下，HAL 已经把字节写进了我们传给 Receive_IT 的那个
  *   缓冲（uart1.c 里的 s_byte），所以不用通过参数传，直接读 s_byte 即可。
  */
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
  /* 本工程四个串口都可能调用这个回调，必须按 Instance 区分，
   * 否则串口屏的数据会被当成上位机数据解析，帧全乱。 */
  if (huart->Instance == USART1) {
    Uart1_OnRxByteFromIsr();      /* USART1 = 串口屏 */
  }
  /* 以后串口屏(USART1)、陀螺仪(USART6)、调试口(USART3) 也走 IT 时，
   * 在这里加对应的 else if 分支即可。 */
}

/**
  * @brief  接收错误回调（由 HAL 在中断上下文里调用）
  *
  * ── 为什么必须实现这个回调 ─────────────────────────────────────────
  *   HAL 的默认实现是空的（__weak），什么也不做，看起来"人畜无害"，
  *   但溢出错误(ORE)的处理路径里有一句 UART_EndRxTransfer()：
  *   它会关掉 RXNEIE / PEIE / EIE，把 RxState 置回 READY，
  *   **然后不会重新武装接收**。
  *
  *   于是只要发生过一次 ORE（比如复位前串口助手已经开好、
  *   上位机先发了一两个字节，RXNE 还没人读，再来一个就 ORE），
  *   接收就会永久停摆：TX 照常发心跳，RX 一个字节都收不到，
  *   而且没有任何报错提示。这就是本次的故障点。
  *
  *   所以这里要：清标志 + 重新武装，让接收永远能自己爬起来。
  */
void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart)
{
  if ((huart->Instance == USART1) &&
      ((huart->ErrorCode & HAL_UART_ERROR_ORE) != 0U)) {
    Uart1_OnRxError();            /* 清 ORE + 重新武装 USART1 接收 */
  }
  /* FE/NE 这类错误 HAL 走的是"非阻断"路径，接收不会停，这里不用管；
   * 真要区别对待时，按 ErrorCode 的位再加分支即可。 */
}
